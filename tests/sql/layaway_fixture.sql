-- Forced journal failure after the RPC updates layaway balance:
-- PostgreSQL must rollback the balance and omit the idempotency receipt.
CREATE FUNCTION public.reject_test_payment() RETURNS trigger
LANGUAGE plpgsql AS $test$
BEGIN
 IF NEW.payment_amount=13.37 THEN
   RAISE EXCEPTION 'Synthetic payment journal failure';
 END IF;
 RETURN NEW;
END;
$test$;
CREATE TRIGGER layaway_payment_rollback_probe BEFORE INSERT ON public.layaway_payments
FOR EACH ROW EXECUTE FUNCTION public.reject_test_payment();


