-- Simula fallar la escritura de historial tras crear una venta final.
CREATE FUNCTION public.simulate_payment_history_failure()
RETURNS trigger LANGUAGE plpgsql AS $failure$
BEGIN
  IF current_setting('atlas.fail_history',true)='on' THEN
    RAISE EXCEPTION 'Synthetic history failure';
  END IF;
  RETURN NEW;
END;
$failure$;
CREATE TRIGGER simulate_payment_history_failure
BEFORE INSERT ON public.layaway_payments FOR EACH ROW
EXECUTE FUNCTION public.simulate_payment_history_failure();
