CREATE TABLE public.layaways (
 id bigint PRIMARY KEY,
 created_at timestamptz DEFAULT now(),
 customer_name text NOT NULL,customer_phone text,
 total numeric,deposit numeric,balance numeric,due_date date,
 status text DEFAULT 'active',items jsonb,notes text
);
CREATE TABLE public.sales (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sale_date timestamptz DEFAULT now(),
 total numeric,profit numeric,received numeric,change_amount numeric,
 items_count integer,subtotal_original numeric,discount_percent numeric,
 discount_amount numeric,status text DEFAULT 'completed',
 updated_at timestamptz DEFAULT now()
);
CREATE TABLE public.sale_items (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sale_id bigint REFERENCES public.sales(id),
 product_id bigint,code text,name text,qty integer,cost numeric,
 price numeric,subtotal numeric,profit numeric
);
CREATE TABLE public.layaway_payments (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 created_at timestamptz NOT NULL DEFAULT now(),
 layaway_id bigint REFERENCES public.layaways(id),
 payment_amount numeric NOT NULL DEFAULT 0,
 previous_balance numeric NOT NULL DEFAULT 0,
 new_balance numeric NOT NULL DEFAULT 0,
 previous_deposit numeric NOT NULL DEFAULT 0,
 new_deposit numeric NOT NULL DEFAULT 0,
 payment_type text NOT NULL DEFAULT 'payment',
 sale_id bigint REFERENCES public.sales(id),
 customer_name text,customer_phone text,total numeric NOT NULL DEFAULT 0,
 due_date date,items jsonb DEFAULT '[]'::jsonb
);
